import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const mockupsDir = path.join(__dirname, 'src', 'components', 'mockups');
const generatedDir = path.join(__dirname, 'src', '.generated');
const outputFile = path.join(generatedDir, 'mockup-components.ts');

function findTsxFiles(dir, fileList = []) {
  if (!fs.existsSync(dir)) return fileList;
  const files = fs.readdirSync(dir);
  for (const file of files) {
    const filePath = path.join(dir, file);
    if (fs.statSync(filePath).isDirectory()) {
      findTsxFiles(filePath, fileList);
    } else if (file.endsWith('.tsx')) {
      fileList.push(filePath);
    }
  }
  return fileList;
}

function generateMap() {
  if (!fs.existsSync(generatedDir)) {
    fs.mkdirSync(generatedDir, { recursive: true });
  }

  const files = findTsxFiles(mockupsDir);
  
  let content = `// This file is auto-generated by gen-mockup-map.mjs.\n`;
  content += `type ModuleMap = Record<string, () => Promise<Record<string, unknown>>>;\n\n`;
  content += `export const modules: ModuleMap = {\n`;
  
  for (let i = 0; i < files.length; i++) {
    const filePath = files[i];
    const relativePath = path.relative(path.join(__dirname, 'src'), filePath);
    // Convert backslashes to forward slashes for import paths
    const importPath = `./${relativePath.replace(/\\/g, '/')}`;
    // Path relative to .generated folder for dynamic import
    const dynamicImportPath = `../${relativePath.replace(/\\/g, '/')}`;
    
    content += `  "${importPath}": () => import("${dynamicImportPath}")`;
    if (i < files.length - 1) {
      content += `,\n`;
    } else {
      content += `\n`;
    }
  }
  
  content += `};\n`;
  
  fs.writeFileSync(outputFile, content, 'utf8');
  console.log(`Generated component map with ${files.length} mockups at ${outputFile}`);
}

generateMap();
